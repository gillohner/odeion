//! The build's TIDAL clients, masked (owner, 2026-11-04). `build.rs` includes this file to write
//! `$OUT_DIR/tidal_clients.rs` from the build environment; `project_apps` includes it to read the
//! values back. Only the variable names are in the repository, never a value.
//!
//! Masking keeps the values out of the repository and out of the binary's plain strings; it is
//! not a security boundary: anyone with the binary can recover them.

// build.rs writes with part of this file, the crate reads with the other
#![allow(dead_code)]

/// What each byte is mixed with (with its position).
const MASK: &[u8] = b"odeion:tidal-clients";

/// Masks or unmasks (the same operation both ways).
pub fn mask(value: &[u8]) -> Vec<u8> {
    value
        .iter()
        .enumerate()
        .map(|(i, b)| b ^ MASK[i % MASK.len()] ^ (i as u8))
        .collect()
}

/// A client from its two build inputs: both set and not blank, trimmed; else none.
pub fn pair(id: Option<String>, secret: Option<String>) -> Option<(String, String)> {
    let id = id.map(|v| v.trim().to_string()).filter(|v| !v.is_empty())?;
    let secret = secret.map(|v| v.trim().to_string()).filter(|v| !v.is_empty())?;
    Some((id, secret))
}

/// The generated module: one `Option<(&[u8], &[u8])>` constant per client, masked.
pub fn generate(clients: &[(&str, Option<(String, String)>)]) -> String {
    let bytes = |v: &str| {
        mask(v.as_bytes())
            .iter()
            .map(|b| b.to_string())
            .collect::<Vec<_>>()
            .join(", ")
    };
    let mut out = String::from("// Generated by crates/pm-api/build.rs: masked build inputs.\n");
    for (name, client) in clients {
        match client {
            Some((id, secret)) => out.push_str(&format!(
                "pub(super) const {name}: Option<(&[u8], &[u8])> = Some((&[{}], &[{}]));\n",
                bytes(id),
                bytes(secret)
            )),
            None => out.push_str(&format!(
                "pub(super) const {name}: Option<(&[u8], &[u8])> = None;\n"
            )),
        }
    }
    out
}

/// A generated constant back as plain values.
pub fn unmask_pair(c: Option<(&[u8], &[u8])>) -> Option<(String, String)> {
    let (id, secret) = c?;
    let id = String::from_utf8(mask(id)).ok()?;
    let secret = String::from_utf8(mask(secret)).ok()?;
    Some((id, secret))
}

#[cfg(test)]
mod tests {
    use super::*;

    type Const = (String, Option<(Vec<u8>, Vec<u8>)>);

    /// Parse what `generate` wrote back into bytes, as the compiler would.
    fn consts(text: &str) -> Vec<Const> {
        let list = |s: &str| -> Vec<u8> {
            s.split(',')
                .map(str::trim)
                .filter(|x| !x.is_empty())
                .map(|x| x.parse().unwrap())
                .collect()
        };
        text.lines()
            .filter_map(|l| l.strip_prefix("pub(super) const "))
            .map(|l| {
                let name = l.split(':').next().unwrap().to_string();
                let value = l.split_once(" = ").unwrap().1;
                if value.starts_with("None") {
                    return (name, None);
                }
                let parts: Vec<&str> = value.split("&[").skip(1).collect();
                let a = parts[0].split(']').next().unwrap();
                let b = parts[1].split(']').next().unwrap();
                (name, Some((list(a), list(b))))
            })
            .collect()
    }

    /// Fake inputs present: masked in the generated file (no plain value in it), read back exactly;
    /// absent or blank: no client.
    #[test]
    fn build_inputs_are_masked_and_read_back() {
        let device = pair(
            Some("  fake-device-id  ".into()),
            Some("fake-device-secret".into()),
        );
        let pkce = pair(
            Some("fake-browser-id".into()),
            Some(" fake-browser-secret\n".into()),
        );
        let text = generate(&[("DEVICE", device), ("PKCE", pkce)]);
        for plain in [
            "fake-device-id",
            "fake-device-secret",
            "fake-browser-id",
            "fake-browser-secret",
            "fake",
        ] {
            assert!(!text.contains(plain), "a plain value in the generated file");
        }
        let got = consts(&text);
        assert_eq!(got.len(), 2);
        let back = |i: usize| {
            let (a, b) = got[i].1.as_ref().unwrap();
            unmask_pair(Some((a.as_slice(), b.as_slice()))).unwrap()
        };
        assert_eq!(got[0].0, "DEVICE");
        assert_eq!(back(0), ("fake-device-id".into(), "fake-device-secret".into()));
        assert_eq!(got[1].0, "PKCE");
        assert_eq!(back(1), ("fake-browser-id".into(), "fake-browser-secret".into()));

        for (id, secret) in [
            (None, None),
            (Some("fake-only-id"), None),
            (None, Some("fake-only-secret")),
            (Some("   "), Some("fake-secret")),
            (Some("fake-id"), Some(" \t")),
        ] {
            assert_eq!(pair(id.map(Into::into), secret.map(Into::into)), None);
        }
        let text = generate(&[("DEVICE", None), ("PKCE", None)]);
        assert!(consts(&text).iter().all(|(_, c)| c.is_none()), "{text}");
        assert_eq!(unmask_pair(None), None);
        // The mask is its own inverse and changes every byte's value
        let m = mask(b"abc");
        assert_ne!(m, b"abc");
        assert_eq!(mask(&m), b"abc");
    }
}
