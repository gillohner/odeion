//! Ring transport probe, for the Android emulator check only (cargo feature
//! `ring-transport-probe`; release builds never have it). It runs once in the app process right
//! after the TLS verifier is set up, so its requests go through the same verifier, DNS and
//! sockets as a Pubky Ring sign-in, and it prints one `RINGPROBE {json}` log line per step for
//! `tools/android-ring-probe.py`. Nothing signs in, no identity is used, no grant is sent to a
//! real homeserver.
//!
//! - `fixture`: a signed PKARR packet, put in the client's cache, for a throwaway homeserver key.
//!   Its direct endpoint refuses (the phone's own loopback, nothing listening) and its ICANN
//!   endpoint is `localhost:<port>`, the runner's fixture server reached through `adb reverse`.
//!   `GET /info` and `POST /auth/grant/session` must both go to the ICANN endpoint.
//! - `relay_tls`: the pkarr relays and the auth relay, reached the way pkarr's own relay client
//!   reaches them (reqwest's default verifier: rustls-platform-verifier).
//! - `resolve_*`: the endpoints the default, relay-only and DHT-only clients find for a public
//!   homeserver key, and the transport (`GET /info`) the default client then picks.

use std::num::NonZeroUsize;
use std::sync::atomic::{AtomicU32, Ordering};
use std::sync::{Arc, Mutex};
use std::time::{Duration, Instant};

use futures_util::StreamExt;
use pubky::pkarr::{self, dns::rdata::SVCB, Cache, CacheKey, InMemoryCache, Keypair, SignedPacket};
use pubky::{Method, PubkyHttpClient};
use serde_json::{json, Value};

/// The runner's fixture server, on the phone's loopback through `adb reverse`.
const FIXTURE_PORT: u16 = 18443;
/// Nothing listens here on the phone: the direct endpoint refuses.
const REFUSED_PORT: u16 = 18444;
/// The fixture server's CA (generated by the workflow before the build).
const FIXTURE_CA: &[u8] = include_bytes!(env!("RING_PROBE_CA"));
/// A public homeserver (a server key, not a person): the one in the reported failure.
const PUBLIC_HOMESERVER: &str = pm_pubky::records::PUBLIC_HOMESERVER;
const STEP_TIMEOUT: Duration = Duration::from_secs(45);

fn emit(step: &str, mut v: Value) {
    v["step"] = json!(step);
    tracing::info!(target: "ringprobe", "RINGPROBE {v}");
}

/// An error with all its causes: the app only ever shows the first.
fn chain(e: &(dyn std::error::Error + 'static)) -> String {
    let mut s = e.to_string();
    let mut cur = e.source();
    while let Some(c) = cur {
        s.push_str(" <- ");
        s.push_str(&c.to_string());
        cur = c.source();
    }
    s
}

pub async fn run() {
    let started = Instant::now();
    emit("start", json!({}));
    // Like `ring_connect`: the client exists before the user leaves for Ring, and the grant
    // exchange runs on it when the approval comes back, often after the app sat in the background.
    let held = PubkyHttpClient::new();
    // A second client from the start that nothing uses until the app is back in the foreground.
    let held_clean = PubkyHttpClient::new();
    // The sign-in's own client, used as `ring_connect` uses it: the relay poll runs on it while
    // the app is away, and the grant exchange when the app's wait lets it (`exchange_on_approval`).
    let flow_client = PubkyHttpClient::new();
    // A real sign-in flow (nobody approves it, no identity is used) started as ring_connect
    // starts one: its relay listener runs while the app is away (`relay_restore`).
    let since_trip = crate::ring_wait::trips();
    let pending = ProbeFlow::start();
    fixture().await;
    relay_tls().await;
    public_homeserver().await;
    emit(
        "phase1_done",
        json!({ "ms": started.elapsed().as_millis() as u64 }),
    );
    // The harness sends the app to the background now and brings it back later. A frozen
    // process wakes past this deadline, so the step below runs as an exchange does on return.
    let wall = std::time::SystemTime::now();
    tokio::time::sleep(Duration::from_secs(60)).await;
    let away = wall.elapsed().map(|d| d.as_millis() as u64).unwrap_or_default();
    let resumed = match &held {
        Ok(c) => {
            let info = routed(c, Method::GET, &format!("https://{PUBLIC_HOMESERVER}/info"), None).await;
            let lookup = lookups(c.pkarr(), PUBLIC_HOMESERVER).await;
            json!({ "away_ms": away, "info": info, "lookup": lookup })
        }
        Err(e) => json!({ "away_ms": away, "error": chain(e) }),
    };
    // A plain HTTPS request too: if it fails as well, the process has no network (Android 15+
    // blocks a backgrounded app), not the SDK client.
    let mut resumed = resumed;
    resumed["plain_get"] = plain_get().await;
    emit("after_background", resumed);
    // Ring's approval has come in while the app is away. The app's wait decides when the grant
    // exchange (its homeserver lookup and POST) runs; then the same lookup and request as the
    // exchange, on the flow's client.
    let mut exchange = json!({});
    match &flow_client {
        Ok(c) => {
            // The relay poll, while away.
            exchange["relay_poll_away"] = routed(c, Method::GET, "https://httprelay.pubky.app/", None).await;
            let waited = Instant::now();
            let (states, on_screen) = app_wait().await;
            exchange["waited_ms"] = json!(waited.elapsed().as_millis() as u64);
            exchange["states"] = json!(states);
            exchange["on_screen"] = json!(on_screen);
            // As the sign-in does on a return to the foreground: the newest record first
            exchange["freshened"] = freshened(c.pkarr()).await;
            exchange["info"] =
                routed(c, Method::GET, &format!("https://{PUBLIC_HOMESERVER}/info"), None).await;
            // The record that routing decided on (see `after_return`)
            exchange["decided_on"] = cached_packet(c.pkarr(), PUBLIC_HOMESERVER).await;
        }
        Err(e) => exchange["error"] = json!(chain(e)),
    }
    emit("exchange_on_approval", exchange);
    // Back on screen: the app's own wait (ring_wait::approval) on that flow. A listener that died
    // while away must be resubscribed (resume), not end the sign-in; with no approval coming the
    // wait is still waiting after 20 s.
    let restore = match pending {
        Ok(flow) => {
            let resumes = flow.resumes.clone();
            let errors = flow.errors.clone();
            let relay = crate::ring_wait::relay_host(flow.flow.authorization_url().as_str());
            let outcome = match tokio::time::timeout(
                Duration::from_secs(20),
                crate::ring_wait::approval(
                    flow,
                    since_trip,
                    &relay,
                    443,
                    crate::ring_wait::Stop::begin(crate::ring_wait::DEADLINE),
                    |_| {},
                ),
            )
            .await
            {
                Err(_) => json!("waiting"),
                Ok(Ok(())) => json!("approved"),
                Ok(Err(e)) => json!({ "failed": e }),
            };
            let errors = errors.lock().map(|e| e.clone()).unwrap_or_default();
            json!({
                "relay": relay,
                "outcome": outcome,
                "resumes": resumes.load(Ordering::Acquire),
                "listener_errors": errors,
                "trips": crate::ring_wait::trips() - since_trip,
            })
        }
        Err(e) => json!({ "error": e }),
    };
    emit("relay_restore", restore);
    // The harness brings the app back. As soon as the network answers again, the exchange an
    // approval waiting on return would make: on the held client (its transport decision from the
    // step above is cached for 60 s) and on a client nothing used in the background.
    let back = Instant::now();
    let mut tries = 0u32;
    while back.elapsed() < Duration::from_secs(150) {
        tries += 1;
        if plain_get().await.get("status").is_some() {
            break;
        }
        tokio::time::sleep(Duration::from_secs(1)).await;
    }
    let waited = back.elapsed().as_millis() as u64;
    let mut on_return = json!({ "waited_ms": waited, "tries": tries });
    for (name, client) in [("held", &held), ("held_clean", &held_clean)] {
        on_return[name] = match client {
            Ok(c) => {
                // As the sign-in does on a return to the foreground: the newest record first
                let fresh = freshened(c.pkarr()).await;
                let info = routed(c, Method::GET, &format!("https://{PUBLIC_HOMESERVER}/info"), None).await;
                // The packet the routing above decided on: the first one the client's lookup got,
                // kept in its cache. The network's newest one comes next (`lookup`): when they
                // differ, the transport was chosen from an older record of the homeserver's.
                let decided_on = cached_packet(c.pkarr(), PUBLIC_HOMESERVER).await;
                json!({
                    "freshened": fresh,
                    "info": info,
                    "decided_on": decided_on,
                    "lookup": lookups(c.pkarr(), PUBLIC_HOMESERVER).await,
                })
            }
            Err(e) => json!({ "error": chain(e) }),
        };
    }
    emit("after_return", on_return);
    emit("done", json!({ "ms": started.elapsed().as_millis() as u64 }));
}

/// A sign-in flow for `relay_restore`, polled and resumed the way `ring_connect`'s `RingFlow` is.
struct ProbeFlow {
    flow: pubky::PubkyGrantAuthFlow,
    resumes: Arc<AtomicU32>,
    errors: Arc<Mutex<Vec<String>>>,
}

impl ProbeFlow {
    fn start() -> Result<Self, String> {
        let client = PubkyHttpClient::new().map_err(|e| chain(&e))?;
        let caps = "/pub/pubky.music/:r"
            .parse::<pubky::Capabilities>()
            .map_err(|e| e.to_string())?;
        let id = pubky::ClientId::new("odeion-ring-probe").map_err(|e| e.to_string())?;
        let flow = pubky::Pubky::with_client(client)
            .start_grant_auth_flow(&caps, pubky::AuthFlowKind::signin(), id)
            .map_err(|e| chain(&e))?;
        Ok(Self {
            flow,
            resumes: Arc::default(),
            errors: Arc::default(),
        })
    }
}

impl crate::ring_wait::Pending for ProbeFlow {
    type Done = ();
    async fn poll(&self) -> Result<Option<()>, crate::ring_wait::Failed> {
        let (r, at_once) = crate::ring_wait::at_once(self.flow.try_poll_once()).await;
        match r {
            Ok(Some(_)) => Ok(Some(())),
            Ok(None) => Ok(None),
            Err(e) => {
                let c = chain(&e);
                if let Ok(mut v) = self.errors.lock() {
                    v.push(c.clone());
                }
                let (transient, server) = match &e {
                    pubky::Error::Request(pubky::errors::RequestError::Transport(_)) => (true, false),
                    pubky::Error::Request(pubky::errors::RequestError::Server { status, .. }) => {
                        (status.is_server_error(), status.is_server_error())
                    }
                    _ => (false, false),
                };
                let relay = crate::ring_wait::relay_host(self.flow.authorization_url().as_str());
                Err(crate::ring_wait::Failed::sort(
                    c, at_once, transient, server, &relay,
                ))
            }
        }
    }
    fn resume(&self) -> Result<Self, String> {
        let state = self.flow.save_local().ok_or("no saved state")?;
        let client = PubkyHttpClient::new().map_err(|e| chain(&e))?;
        let flow = pubky::PubkyGrantAuthFlow::restore(state, client).map_err(|e| chain(&e))?;
        self.resumes.fetch_add(1, Ordering::AcqRel);
        Ok(Self {
            flow,
            resumes: self.resumes.clone(),
            errors: self.errors.clone(),
        })
    }
}

/// The app's wait between Ring's approval arriving and the grant exchange (`ring_wait`, which
/// `ring_connect` runs before each poll): returns the page states it showed and whether it ended
/// with the app on screen.
async fn app_wait() -> (Vec<&'static str>, Option<bool>) {
    let mut states = Vec::new();
    let stop = crate::ring_wait::Stop::begin(crate::ring_wait::DEADLINE);
    let _ = crate::ring_wait::until_ready("httprelay.pubky.app", 443, &stop, |s| states.push(s)).await;
    (states, Some(crate::ring_wait::on_screen()))
}

/// One plain HTTPS GET to the homeserver's ICANN name (no PKARR), 5 s at most.
async fn plain_get() -> Value {
    let started = Instant::now();
    let client = match reqwest::Client::builder().timeout(Duration::from_secs(5)).build() {
        Ok(c) => c,
        Err(e) => return json!({ "error": chain(&e) }),
    };
    match client.get("https://homeserver.riginode.xyz/info").send().await {
        Ok(r) => json!({ "status": r.status().as_u16(), "ms": started.elapsed().as_millis() as u64 }),
        Err(e) => json!({ "error": chain(&e), "ms": started.elapsed().as_millis() as u64 }),
    }
}

/// The sign-in's own step before any request to the public homeserver: its newest record,
/// network-first (`pm_pubky::records::freshen`), as `ring_connect` does.
async fn freshened(pkarr: &pkarr::Client) -> Value {
    let started = Instant::now();
    let r = pm_pubky::records::freshen(pkarr, &[PUBLIC_HOMESERVER]).await;
    json!({ "records": r, "ms": started.elapsed().as_millis() as u64 })
}

/// The signed packet the client holds for `z32` right now (cache only): its time and the targets
/// of its HTTPS records (`.` for the direct endpoint, else an ICANN domain or a key).
async fn cached_packet(pkarr: &pkarr::Client, z32: &str) -> Value {
    let pk = match pkarr::PublicKey::try_from(z32) {
        Ok(pk) => pk,
        Err(e) => return json!({ "error": e.to_string() }),
    };
    match pkarr.resolve(&pk, pkarr::ResolvePolicy::CacheOnly).await {
        Err(e) => json!({ "error": chain(&e) }),
        Ok(p) => {
            let targets: Vec<String> = p
                .all_resource_records()
                .filter_map(|r| match &r.rdata {
                    pkarr::dns::rdata::RData::HTTPS(h) => Some(h.0.target.to_string()),
                    _ => None,
                })
                .collect();
            json!({ "timestamp_us": p.timestamp().as_u64(), "targets": targets })
        }
    }
}

/// The packet each backend answers with (network only), and the endpoints it gives.
async fn lookups(pkarr: &pkarr::Client, z32: &str) -> Value {
    let started = Instant::now();
    let packet = match pkarr::PublicKey::try_from(z32) {
        Err(e) => json!({ "error": e.to_string() }),
        Ok(pk) => match tokio::time::timeout(
            STEP_TIMEOUT,
            pkarr.resolve(&pk, pkarr::ResolvePolicy::NetworkOnly),
        )
        .await
        {
            Err(_) => json!({ "error": "timed out" }),
            Ok(Err(e)) => json!({ "error": chain(&e) }),
            Ok(Ok(p)) => json!({ "timestamp_us": p.timestamp().as_u64(), "bytes": p.encoded_packet().len() }),
        },
    };
    json!({ "packet": packet, "packet_ms": started.elapsed().as_millis() as u64, "endpoints": endpoints(pkarr, z32).await })
}

/// Build a request through the SDK's transport routing, note where it goes, then send it.
async fn routed(client: &PubkyHttpClient, method: Method, url: &str, body: Option<Value>) -> Value {
    let started = Instant::now();
    let url = match url::Url::parse(url) {
        Ok(u) => u,
        Err(e) => return json!({ "error": e.to_string() }),
    };
    let rb = match tokio::time::timeout(STEP_TIMEOUT, client.request_async(method, url)).await {
        Err(_) => return json!({ "error": "routing timed out", "ms": started.elapsed().as_millis() as u64 }),
        Ok(Err(e)) => return json!({ "error": chain(&e), "stage": "routing" }),
        Ok(Ok(rb)) => rb,
    };
    let rb = match body {
        Some(b) => rb.json(&b),
        None => rb,
    };
    let (http, req) = rb.build_split();
    let req = match req {
        Ok(r) => r,
        Err(e) => return json!({ "error": chain(&e), "stage": "build" }),
    };
    let sent_to = req.url().to_string();
    let host = req.url().host_str().unwrap_or_default().to_string();
    let outcome = match tokio::time::timeout(STEP_TIMEOUT, http.execute(req)).await {
        Err(_) => json!({ "error": "send timed out" }),
        Ok(Err(e)) => json!({ "error": chain(&e) }),
        Ok(Ok(r)) => json!({ "status": r.status().as_u16() }),
    };
    json!({ "sent_to": sent_to, "host": host, "outcome": outcome, "ms": started.elapsed().as_millis() as u64 })
}

async fn endpoints(pkarr: &pkarr::Client, qname: &str) -> Value {
    let started = Instant::now();
    let collect = async {
        let stream = pkarr.resolve_https_endpoints(qname);
        futures_util::pin_mut!(stream);
        let mut out = Vec::new();
        while let Some(ep) = stream.next().await {
            out.push(json!({
                "domain": ep.domain(),
                "port": ep.port(),
                "addrs": ep.to_socket_addrs().iter().map(|a| a.to_string()).collect::<Vec<_>>(),
            }));
        }
        out
    };
    match tokio::time::timeout(STEP_TIMEOUT, collect).await {
        Ok(eps) => json!({ "endpoints": eps, "ms": started.elapsed().as_millis() as u64 }),
        Err(_) => json!({ "error": "timed out", "ms": started.elapsed().as_millis() as u64 }),
    }
}

async fn fixture() {
    let homeserver = Keypair::random();
    let packet = {
        let mut direct = SVCB::new(1, ".".try_into().expect("root name"));
        direct.set_port(REFUSED_PORT);
        let mut icann = SVCB::new(10, "localhost".try_into().expect("domain name"));
        icann.set_port(FIXTURE_PORT);
        SignedPacket::builder()
            .https(".".try_into().expect("root name"), direct, 3600)
            .https(".".try_into().expect("root name"), icann, 3600)
            .address(
                ".".try_into().expect("root name"),
                "127.0.0.1".parse().expect("ip"),
                3600,
            )
            .sign(&homeserver)
    };
    let packet = match packet {
        Ok(p) => p,
        Err(e) => return emit("fixture", json!({ "error": chain(&e) })),
    };
    let cache = Arc::new(InMemoryCache::new(NonZeroUsize::new(8).expect("non-zero")));
    let key: CacheKey = homeserver.public_key().into();
    cache.put(&key, &packet);
    let mut builder = PubkyHttpClient::builder();
    // No DHT and a relay that is not there: only the cached packet answers.
    builder.pkarr(|p| {
        p.no_dht();
        p.relays(&["http://127.0.0.1:9/"]).expect("relay url");
        p.cache(cache.clone() as Arc<dyn Cache>)
    });
    if let Err(e) = builder.add_root_certificates_pem(FIXTURE_CA) {
        return emit("fixture", json!({ "error": chain(&e) }));
    }
    let client = match builder.build() {
        Ok(c) => c,
        Err(e) => return emit("fixture", json!({ "error": chain(&e) })),
    };
    let hs = homeserver.public_key().to_string();
    let info = routed(&client, Method::GET, &format!("https://{hs}/info"), None).await;
    let grant = routed(
        &client,
        Method::POST,
        &format!("https://{hs}/auth/grant/session"),
        Some(json!({ "grant": "ring-probe-fixture", "pop": "ring-probe-fixture" })),
    )
    .await;
    emit(
        "fixture",
        json!({ "homeserver": hs, "icann": format!("localhost:{FIXTURE_PORT}"), "direct": format!("127.0.0.1:{REFUSED_PORT}"), "info": info, "grant": grant }),
    );
}

async fn relay_tls() {
    // What pkarr builds when given no client (pkarr 8 `RelayBackend::new`).
    let client = match reqwest::Client::builder().build() {
        Ok(c) => c,
        Err(e) => return emit("relay_tls", json!({ "error": chain(&e) })),
    };
    let mut results = Vec::new();
    for url in pkarr::DEFAULT_RELAYS
        .iter()
        .map(|r| format!("{}/{PUBLIC_HOMESERVER}", r.trim_end_matches('/')))
        .chain([
            "https://httprelay.pubky.app/".to_string(),
            "https://homeserver.riginode.xyz/info".to_string(),
        ])
    {
        let started = Instant::now();
        let outcome = match tokio::time::timeout(STEP_TIMEOUT, client.get(&url).send()).await {
            Err(_) => json!({ "error": "timed out" }),
            Ok(Err(e)) => json!({ "error": chain(&e) }),
            Ok(Ok(r)) => json!({ "status": r.status().as_u16() }),
        };
        results.push(json!({ "url": url, "outcome": outcome, "ms": started.elapsed().as_millis() as u64 }));
    }
    emit("relay_tls", json!({ "results": results }));
}

async fn public_homeserver() {
    let direct = {
        let started = Instant::now();
        let addr: std::net::SocketAddr = "139.162.128.88:6287".parse().expect("addr");
        // The SDK's own probe: a TCP connect within 1.5 s.
        let r = tokio::task::spawn_blocking(move || {
            std::net::TcpStream::connect_timeout(&addr, Duration::from_millis(1500))
        })
        .await;
        json!({
            "addr": addr.to_string(),
            "reachable": matches!(r, Ok(Ok(_))),
            "detail": match r { Err(e) => e.to_string(), Ok(Err(e)) => e.to_string(), Ok(Ok(_)) => "connected".into() },
            "ms": started.elapsed().as_millis() as u64,
        })
    };
    emit("direct_tcp", direct);
    for (name, configure) in [
        ("resolve_relays", Some(true)),
        ("resolve_dht", Some(false)),
        ("resolve_default", None),
    ] {
        let mut builder = PubkyHttpClient::builder();
        match configure {
            Some(true) => {
                builder.pkarr(|p| p.no_dht());
            }
            Some(false) => {
                builder.pkarr(|p| p.no_relays());
            }
            None => {}
        }
        let client = match builder.build() {
            Ok(c) => c,
            Err(e) => {
                emit(name, json!({ "error": chain(&e) }));
                continue;
            }
        };
        let eps = lookups(client.pkarr(), PUBLIC_HOMESERVER).await;
        // The default client is the one Ring sign-in uses (`Pubky::new`): where would it send?
        let (info, decided_on) = if configure.is_none() {
            // A fresh client, so the endpoint lookup above cannot have warmed its caches.
            match PubkyHttpClient::new() {
                Ok(c) => {
                    // As the sign-in does before it starts: the newest record first
                    let fresh = freshened(c.pkarr()).await;
                    let info = routed(
                        &c,
                        Method::GET,
                        &format!("https://{PUBLIC_HOMESERVER}/info"),
                        None,
                    )
                    .await;
                    // The record that routing decided on (see `after_return`)
                    (
                        json!({ "freshened": fresh, "request": info }),
                        cached_packet(c.pkarr(), PUBLIC_HOMESERVER).await,
                    )
                }
                Err(e) => (json!({ "error": chain(&e) }), Value::Null),
            }
        } else {
            (Value::Null, Value::Null)
        };
        let (freshened_v, info) = match info {
            Value::Object(mut m) if m.contains_key("request") => (
                m.remove("freshened").unwrap_or(Value::Null),
                m.remove("request").unwrap_or(Value::Null),
            ),
            other => (Value::Null, other),
        };
        emit(
            name,
            json!({ "homeserver": PUBLIC_HOMESERVER, "lookup": eps, "freshened": freshened_v, "info": info, "decided_on": decided_on }),
        );
    }
}
